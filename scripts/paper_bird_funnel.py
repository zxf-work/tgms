#!/usr/bin/env python
"""Emit fig-bird-funnel.tex from the BIRD agent-arm receipt.

The certification funnel over the frozen 500-question universe:
universe -> executable SQL -> typed claim constructed -> certified ->
certified and correct, with each stage's exit reason annotated on the
drop. Fully generated from benchmarks/results-v1/eval-bird-agent.json;
re-running regenerates byte-for-byte.

    python scripts/paper_bird_funnel.py --outdir paper/ecqr
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

REC = Path("benchmarks/results-v1/eval-bird-agent.json")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", type=Path, required=True)
    args = ap.parse_args()

    r = json.loads(REC.read_text())
    fu = r["funnel"]
    stages = [
        ("Frozen universe", fu["universe"], None),
        ("Executable SQL", fu["executable_sql"],
         f"$-{fu['universe'] - fu['executable_sql']}$ no SQL"),
        ("Typed claim constructed", fu["claim_constructed"],
         f"$-{fu['executable_sql'] - fu['claim_constructed']}$ "
         "shape mismatch"),
        ("Certified", fu["certified"],
         f"$-{fu['claim_constructed'] - fu['certified']}$ withheld"),
        ("Certified and correct", fu["certified_and_correct"],
         f"$-{fu['certified'] - fu['certified_and_correct']}$ "
         "wrong query"),
    ]
    names = [s[0] for s in stages]
    ycoords = ",".join(reversed(names))
    bars = " ".join(f"({v},{n})" for n, v, _ in stages)
    # annotations are column-aligned to the right of the longest bar
    note_x = int(fu["universe"] * 1.12)
    drops = [
        rf"\node[anchor=west, font=\tiny, text=black!55] at "
        rf"(axis cs:{note_x},{{{name}}}) {{{note}}};"
        for name, _v, note in stages if note is not None]
    # support x correctness: the paper's central boundary in four cells
    cc = fu["certified_and_correct"]
    cw = fu["certified"] - cc
    nc_right = r["em_overall"] - cc
    nc_wrong = fu["universe"] - fu["certified"] - nc_right
    cells = [
        (0, 1, cc, "black!12"), (1, 1, cw, "black!5"),
        (0, 0, nc_right, "black!5"), (1, 0, nc_wrong, "white"),
    ]
    matrix = []
    for x, y, v, fill in cells:
        matrix.append(
            rf"\draw[fill={fill}, draw=black!45] ({x*1.5},{y*0.85}) "
            rf"rectangle ({x*1.5+1.5},{y*0.85+0.85});")
        matrix.append(
            rf"\node[font=\small] at ({x*1.5+0.75},{y*0.85+0.42}) "
            rf"{{{v}}};")

    tex = "\n".join([
        "% GENERATED by scripts/paper_bird_funnel.py -- do not edit.",
        "% Source: benchmarks/results-v1/eval-bird-agent.json.",
        r"\begin{figure}[t]",
        r"\centering",
        r"\begin{tikzpicture}",
        r"\begin{axis}[xbar, width=0.94\linewidth, height=3.9cm,",
        rf"  symbolic y coords={{{ycoords}}}, ytick=data,",
        r"  xmin=0, xmax=" + str(int(fu["universe"] * 1.62)) + ",",
        r"  xtick={0,250,500},",
        r"  y tick label style={font=\scriptsize},",
        r"  x tick label style={font=\tiny},",
        r"  bar width=7pt, nodes near coords,",
        r"  every node near coord/.append style={font=\tiny},",
        r"  axis x line*=bottom, axis y line*=left]",
        rf"\addplot+[fill=black!25, draw=black!70] coordinates "
        rf"{{{bars}}};",
        *drops,
        r"\end{axis}",
        # lower panel: support x correctness
        r"\begin{scope}[yshift=-2.55cm, xshift=1.75cm]",
        *matrix,
        r"\node[font=\scriptsize, anchor=south] at (0.75,1.74) "
        r"{gold-correct};",
        r"\node[font=\scriptsize, anchor=south] at (2.25,1.74) "
        r"{gold-mismatch};",
        r"\node[font=\scriptsize, anchor=east] at (-0.10,1.27) "
        r"{certified};",
        r"\node[font=\scriptsize, anchor=east] at (-0.10,0.42) "
        r"{no claim};",
        r"\end{scope}",
        r"\end{tikzpicture}",
        r"\caption{BIRD Mini-Dev, frozen 500-question universe and a "
        r"single frozen configuration. \emph{Top}: the certification "
        r"funnel; each drop is an exit the contract makes explicit. "
        r"\emph{Bottom}: support against correctness. The right-hand "
        r"column is not certification failure --- those values are "
        r"supported by the query that ran, whose result disagrees with "
        r"benchmark gold --- and the bottom-left cell is the "
        r"correct-answer cost of the contract.}",
        r"\label{fig:birdfunnel}",
        r"\end{figure}",
        ""])
    out = args.outdir / "fig-bird-funnel.tex"
    out.write_text(tex)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
